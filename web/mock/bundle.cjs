// Copies every mock/*.json file into mock/mock-data.js so the dashboard can run from file://,
// where browsers block fetch() of local JSON. The JSON files stay the source of truth.
// Run after editing any mock file:  node mock/bundle.cjs
const fs = require('fs');
const path = require('path');
const dir = __dirname;
const out = {};
fs.readdirSync(dir).filter(f => f.endsWith('.json')).sort().forEach(f => {
  out[f] = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
});
const js = '// Generated by mock/bundle.cjs from the JSON files in this folder. Do not edit by hand.\n' +
  'window.MIRSAD_MOCK = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(dir, 'mock-data.js'), js);
console.log('mock-data.js written with', Object.keys(out).length, 'files:', Object.keys(out).join(', '));
